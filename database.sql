-- Row Level Security: data user hanya dapat dibaca/dibuat oleh pemiliknya.
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.oil_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pickup_schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rewards ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reward_redemptions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Read own profile" ON public.profiles;
CREATE POLICY "Read own profile" ON public.profiles
    FOR SELECT USING (auth.uid() = id);
DROP POLICY IF EXISTS "Update own profile" ON public.profiles;
CREATE POLICY "Update own profile" ON public.profiles
    FOR UPDATE USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Read own transactions" ON public.oil_transactions;
CREATE POLICY "Read own transactions" ON public.oil_transactions
    FOR SELECT USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Create own transactions" ON public.oil_transactions;
CREATE POLICY "Create own transactions" ON public.oil_transactions
    FOR INSERT WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Read own pickup schedules" ON public.pickup_schedules;
CREATE POLICY "Read own pickup schedules" ON public.pickup_schedules
    FOR SELECT USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Create own pickup schedules" ON public.pickup_schedules;
CREATE POLICY "Create own pickup schedules" ON public.pickup_schedules
    FOR INSERT WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Anyone can read active rewards" ON public.rewards;
CREATE POLICY "Anyone can read active rewards" ON public.rewards
    FOR SELECT USING (is_active = TRUE);

DROP POLICY IF EXISTS "Read own reward redemptions" ON public.reward_redemptions;
CREATE POLICY "Read own reward redemptions" ON public.reward_redemptions
    FOR SELECT USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Create own reward redemptions" ON public.reward_redemptions;
CREATE POLICY "Create own reward redemptions" ON public.reward_redemptions
    FOR INSERT WITH CHECK (auth.uid() = user_id);

